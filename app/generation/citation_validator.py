from __future__ import annotations

import re
from typing import TYPE_CHECKING, Optional

from app.core.logging import get_logger
from app.generation.prompt_builder import INSUFFICIENT_EVIDENCE_MARKER
from app.schemas.qa import Citation

if TYPE_CHECKING:
    from app.retrieval.hybrid_retriever import RetrievedChunk

logger = get_logger(__name__)

# Match [SOURCE N] references in the LLM's output
_SOURCE_REF_RE = re.compile(r"\[SOURCE\s+(\d+)\]", re.IGNORECASE)


class CitationValidator:
    """Validates and extracts citations from LLM output.

    Design principle: Citations are derived from retrieval metadata, never from
    LLM-generated text.  The LLM is only allowed to reference [SOURCE N] labels.
    We map those labels back to actual chunk metadata from the retrieval step.

    This means:
    - If the LLM invents a source number that doesn't exist in source_map → rejected.
    - If the LLM claims [SOURCE 3] → we look up source_map[3] → chunk_id
      → fetch the real metadata from the retrieved chunks list.
    - The filename, page, heading, and excerpt in the Citation come from SQLite,
      not from the LLM's text.
    """

    def validate_and_extract(
        self,
        llm_output: str,
        source_map: dict[int, str],
        retrieved_chunks: list["RetrievedChunk"],
    ) -> tuple[Optional[str], list[Citation]]:
        """Parse LLM output, validate cited sources, and return clean citations.

        Args:
            llm_output: Raw text generated by the LLM.
            source_map: {source_number → chunk_id} mapping from PromptBuilder.
            retrieved_chunks: The full list of retrieved chunks (for metadata).

        Returns:
            Tuple of:
            - answer: Cleaned answer text (None if insufficient evidence).
            - citations: List of validated Citation objects.
        """
        # Detect abstention
        if INSUFFICIENT_EVIDENCE_MARKER in llm_output:
            return None, []

        # Check for empty or trivially useless output
        cleaned = llm_output.strip()
        if not cleaned or len(cleaned) < 5:
            return None, []

        # Find all [SOURCE N] references in the output
        cited_numbers = set(int(m) for m in _SOURCE_REF_RE.findall(llm_output))

        # Build chunk_id lookup from retrieved chunks
        chunk_lookup: dict[str, "RetrievedChunk"] = {c.chunk_id: c for c in retrieved_chunks}

        citations: list[Citation] = []
        seen_chunk_ids: set[str] = set()

        for source_num in sorted(cited_numbers):
            chunk_id = source_map.get(source_num)
            if chunk_id is None:
                # LLM cited a source number that doesn't exist → reject
                logger.warning(
                    "LLM cited [SOURCE %d] but source_map has no such entry. Rejected.",
                    source_num,
                )
                continue

            if chunk_id in seen_chunk_ids:
                continue  # Deduplicate

            chunk = chunk_lookup.get(chunk_id)
            if chunk is None:
                logger.warning("chunk_id %r from source_map not found in retrieved_chunks.", chunk_id)
                continue

            excerpt = chunk.text[:250].replace("\n", " ").strip()
            if len(chunk.text) > 250:
                excerpt += "…"

            citations.append(
                Citation(
                    chunk_id=chunk.chunk_id,
                    document_id=chunk.document_id,
                    filename=chunk.filename,
                    page_number=chunk.page_number,
                    section_heading=chunk.section_heading,
                    relevance_score=round(chunk.rrf_score, 4),
                    excerpt=excerpt,
                )
            )
            seen_chunk_ids.add(chunk_id)

        # If no explicit [SOURCE N] tags were attempted in text, attribute the top relevant retrieved chunk
        if not cited_numbers and not citations and retrieved_chunks and cleaned:
            top_chunk = retrieved_chunks[0]
            excerpt = top_chunk.text[:250].replace("\n", " ").strip()
            if len(top_chunk.text) > 250:
                excerpt += "…"
            citations.append(
                Citation(
                    chunk_id=top_chunk.chunk_id,
                    document_id=top_chunk.document_id,
                    filename=top_chunk.filename,
                    page_number=top_chunk.page_number,
                    section_heading=top_chunk.section_heading,
                    relevance_score=round(top_chunk.rrf_score, 4),
                    excerpt=excerpt,
                )
            )

        return cleaned, citations

    @staticmethod
    def is_insufficient_evidence(llm_output: str) -> bool:
        """Return True if the LLM indicated it could not find evidence."""
        return INSUFFICIENT_EVIDENCE_MARKER in llm_output or not llm_output.strip()
